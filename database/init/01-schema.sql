CREATE TABLE tercero (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo_documento        VARCHAR(5)   NOT NULL CHECK (tipo_documento IN ('CC', 'CE', 'NIT', 'PA', 'TI')),
    numero_documento      VARCHAR(20)  NOT NULL,
    tipo_persona          VARCHAR(10)  NOT NULL CHECK (tipo_persona IN ('NATURAL', 'JURIDICA')),
    nombre_razon_social   VARCHAR(200) NOT NULL,
    email                 VARCHAR(150),
    celular               VARCHAR(20),
    acepta_notificaciones BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT uk_tercero_documento UNIQUE (tipo_documento, numero_documento)
);

CREATE TABLE inmueble (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    matricula_inmobiliaria VARCHAR(30)  NOT NULL,
    direccion              VARCHAR(200) NOT NULL,
    ciudad                 VARCHAR(100) NOT NULL,
    tipo                   VARCHAR(15)  NOT NULL CHECK (tipo IN ('VIVIENDA', 'COMERCIAL')),
    CONSTRAINT uk_inmueble_matricula UNIQUE (matricula_inmobiliaria)
);

CREATE TABLE poliza (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero_poliza         VARCHAR(30)    NOT NULL,
    tipo                  VARCHAR(15)    NOT NULL CHECK (tipo IN ('INDIVIDUAL', 'COLECTIVA')),
    tomador_id            BIGINT         NOT NULL REFERENCES tercero (id),
    fecha_inicio          DATE           NOT NULL,
    fecha_fin             DATE           NOT NULL,
    meses_vigencia        INTEGER        NOT NULL CHECK (meses_vigencia > 0),
    canon_mensual         NUMERIC(15, 2) NOT NULL CHECK (canon_mensual >= 0),
    valor_prima           NUMERIC(15, 2) NOT NULL CHECK (valor_prima >= 0),
    estado                VARCHAR(15)    NOT NULL CHECK (estado IN ('VIGENTE', 'RENOVADA', 'CANCELADA', 'VENCIDA')),
    renovacion_automatica BOOLEAN        NOT NULL DEFAULT TRUE,
    numero_renovacion     INTEGER        NOT NULL DEFAULT 0,
    estado_sync_core      VARCHAR(15)    NOT NULL DEFAULT 'PENDIENTE' CHECK (estado_sync_core IN ('PENDIENTE', 'SINCRONIZADO', 'ERROR')),
    numero_poliza_core    VARCHAR(30),
    version               INTEGER        NOT NULL DEFAULT 0,
    CONSTRAINT uk_poliza_numero UNIQUE (numero_poliza),
    CONSTRAINT ck_poliza_fechas CHECK (fecha_fin > fecha_inicio)
);

CREATE INDEX ix_poliza_tipo_estado ON poliza (tipo, estado);

CREATE TABLE riesgo (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    poliza_id          BIGINT         NOT NULL REFERENCES poliza (id),
    inmueble_id        BIGINT         NOT NULL REFERENCES inmueble (id),
    asegurado_id       BIGINT         NOT NULL REFERENCES tercero (id),
    beneficiario_id    BIGINT         NOT NULL REFERENCES tercero (id),
    canon_mensual      NUMERIC(15, 2) NOT NULL CHECK (canon_mensual > 0),
    valor_prima        NUMERIC(15, 2) NOT NULL CHECK (valor_prima > 0),
    fecha_inclusion    DATE           NOT NULL,
    fecha_cancelacion  DATE,
    motivo_cancelacion VARCHAR(200),
    estado             VARCHAR(15)    NOT NULL CHECK (estado IN ('ACTIVO', 'CANCELADO')),
    estado_sync_core   VARCHAR(15)    NOT NULL DEFAULT 'PENDIENTE' CHECK (estado_sync_core IN ('PENDIENTE', 'SINCRONIZADO', 'ERROR')),
    version            INTEGER        NOT NULL DEFAULT 0
);

CREATE INDEX ix_riesgo_poliza ON riesgo (poliza_id);
CREATE UNIQUE INDEX ux_riesgo_inmueble_activo ON riesgo (poliza_id, inmueble_id) WHERE estado = 'ACTIVO';

CREATE TABLE certificado (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    poliza_id          BIGINT         NOT NULL REFERENCES poliza (id),
    numero_certificado INTEGER        NOT NULL,
    tipo_movimiento    VARCHAR(15)    NOT NULL CHECK (tipo_movimiento IN ('EXPEDICION', 'RENOVACION')),
    fecha_inicio       DATE           NOT NULL,
    fecha_fin          DATE           NOT NULL,
    canon_mensual      NUMERIC(15, 2) NOT NULL,
    valor_prima        NUMERIC(15, 2) NOT NULL,
    ipc_aplicado       NUMERIC(6, 4),
    fecha_registro     TIMESTAMP      NOT NULL DEFAULT now(),
    CONSTRAINT uk_certificado_numero UNIQUE (poliza_id, numero_certificado)
);
